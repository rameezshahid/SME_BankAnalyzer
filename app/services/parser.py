import re
import pdfplumber
from datetime import datetime

from app.models.transaction import Transaction


TXN_START_RE = re.compile(
    r"^\s*(\d+)\s+(\d{2}/\d{2}/\d{4})\s+(\d{2}/\d{2}/\d{4})\s+(.+?)\s+(DR|CR)\s+([\d,]+\.\d{2})\s*$"
)

GENERIC_TXN_RE = re.compile(
    r"^\s*(?P<date>\d{2}[/-]\d{2}[/-]\d{2,4}|\d{4}[/-]\d{2}[/-]\d{2})\s+(?P<body>.+?)\s+"
    r"(?:(?P<drcr>DR|CR|DEBIT|CREDIT)\s+)?(?P<amount>-?[\d,]+\.\d{2})(?:\s+(?P<balance>-?[\d,]+\.\d{2}))?\s*$",
    re.IGNORECASE,
)

SNB_TXN_START_RE = re.compile(
    r"^\s*(?P<balance>[\d,]+\.\d{2})\s+(?:(?P<sign>-)\s+)?(?P<amount>[\d,]+\.\d{2})\s+"
    r"(?P<body>.+?)\s+(?P<date>\d{2}/\d{2}/\d{4})\s*$"
)

AL_AWWAL_AMOUNT_RE = re.compile(
    r"^\s*(?P<drcr>DR|CR)\s+(?P<amount>[\d,]+\.\d{2})\s*$",
    re.IGNORECASE,
)

AL_AWWAL_DETAIL_RE = re.compile(
    r"^\s*(?P<body>.+?)\s+(?P<value_date>\d{2}/\d{2}/\d{4})\s+(?P<txn_date>\d{2}/\d{2}/\d{4})\s+(?P<sno>\d+)\s*$"
)

AL_AWWAL_STATEMENT_RE = re.compile(
    r"^\s*(?P<date>\d{2}-[A-Za-z]{3}-\d{2})\s+(?P<body>.+?)\s+"
    r"(?P<amount>[\d,]+\.\d{2})\s+(?P<balance>[\d,]+\.\d{2})\+?\s*$"
)

BSF_TXN_RE = re.compile(
    r"^\s*(?P<txn_date>\d{2}/\d{2}/\d{4})\s+(?P<value_date>\d{2}/\d{2}/\d{4})\s+"
    r"(?P<middle>.+?)\s+(?P<amount>[\d,]+\.\d{2})\s+(?P<balance>[\d,]+\.\d{2})(?:\s+(?P<description>.*))?\s*$"
)

FOOTER_MARKERS = [
    "Opening Balance",
    "Debit Count",
    "Total Debits",
    "Credit Count",
    "Total Credits",
    "Closing Balance",
    "Generate On",
    "Generated Time",
    "Generated By",
    "This is a computer generated statement",
]

def extract_text_from_pdf(file_path: str):
    pages_text = []

    with pdfplumber.open(file_path) as pdf:
        for i, page in enumerate(pdf.pages, start=1):
            text = page.extract_text()
            pages_text.append({
                "page": i,
                "text": text or ""
            })

    return pages_text


def parse_date(date_str):
    formats = (
        "%d/%m/%Y",
        "%d-%m-%Y",
        "%d/%m/%y",
        "%d-%m-%y",
        "%Y-%m-%d",
        "%Y/%m/%d",
        "%d-%b-%y",
    )
    for fmt in formats:
        try:
            return datetime.strptime(date_str.strip(), fmt)
        except Exception:
            continue
    return None


def clean_line(line: str) -> str:
    return " ".join((line or "").strip().split())


def extract_balance(block_lines):
    for line in block_lines:
        m = re.search(r"Balance\s+SAR\s+([\d,]+\.\d{2})", line, re.IGNORECASE)
        if m:
            try:
                return float(m.group(1).replace(",", ""))
            except Exception:
                return None
    return None


def extract_opening_balance(lines):
    for line in lines:
        match = re.search(r"Opening Balance:\s*SAR\s*([\d,]+\.\d{2})", line, re.IGNORECASE)
        if match:
            try:
                return float(match.group(1).replace(",", ""))
            except Exception:
                return None
    return None


def parse_sabb_text(file_path: str):
    pages = extract_text_from_pdf(file_path)

    all_lines = []
    for page in pages:
        lines = page["text"].splitlines()
        for line in lines:
            line = clean_line(line)
            if line:
                if any(x in line for x in [
                    "Opening Balance",
                    "Total Debits",
                    "Total Credits",
                    "Closing Balance",
                    "Generate On",
                    "Generated Time",
                    "Generated By",
                    "This is a computer generated statement",
                    "* Closing balance includes",
                ]):
                    continue
                all_lines.append(line)

    transactions = []
    current = None

    for line in all_lines:
        # skip obvious headers/footers
        if line.startswith("Transaction Date Value Date"):
            continue
        if line.startswith("S.No Remarks Transaction Amount"):
            continue
        if line.startswith("(dd/mm/yyyy)"):
            continue
        if line.startswith("Page No :-"):
            continue
        if "Account Statement for the period" in line:
            continue

        m = TXN_START_RE.match(line)
        if m:
            # finalize previous transaction
            if current:
                transactions.append(build_transaction(current))

            current = {
                "sno": m.group(1),
                "txn_date": m.group(2),
                "value_date": m.group(3),
                "headline": m.group(4),
                "drcr": m.group(5),
                "amount": m.group(6),
                "lines": []
            }
        else:
            if current:
                if any(marker in line for marker in FOOTER_MARKERS):
                    continue
                current["lines"].append(line)

    if current:
        transactions.append(build_transaction(current))

    return [t for t in transactions if t is not None]


def parse_generic_text(file_path: str):
    pages = extract_text_from_pdf(file_path)
    transactions = []

    for page in pages:
        for raw_line in page["text"].splitlines():
            line = clean_line(raw_line)
            if not line:
                continue

            upper = line.upper()
            if any(marker.upper() in upper for marker in FOOTER_MARKERS):
                continue
            if upper.startswith(("DATE ", "TRANSACTION DATE", "VALUE DATE", "ACCOUNT ", "PAGE ")):
                continue

            match = GENERIC_TXN_RE.match(line)
            if not match:
                continue

            txn = build_generic_transaction(match)
            if txn:
                transactions.append(txn)

    return transactions


def parse_snb_business_text(file_path: str):
    pages = extract_text_from_pdf(file_path)
    transactions = []
    current = None

    for page in pages:
        for raw_line in page["text"].splitlines():
            line = clean_line(raw_line)
            if not line:
                continue

            upper = line.upper()
            if upper.startswith(("BALANCE CREDIT/DEBIT", "ACCOUNT STATEMENT", "PAGE NUMBER")):
                continue

            match = SNB_TXN_START_RE.match(line)
            if match:
                if current:
                    transactions.append(build_snb_business_transaction(current))
                current = {
                    "balance": match.group("balance"),
                    "amount": match.group("amount"),
                    "is_debit": bool(match.group("sign")),
                    "body": match.group("body"),
                    "date": match.group("date"),
                    "lines": [],
                }
                continue

            if current:
                if "PAGE NUMBER" in upper or "ACCOUNT NUMBER" in upper:
                    continue
                current["lines"].append(line)

    if current:
        transactions.append(build_snb_business_transaction(current))

    return [txn for txn in transactions if txn is not None]


def build_snb_business_transaction(raw):
    try:
        amount = float(raw["amount"].replace(",", ""))
        signed_amount = -amount if raw["is_debit"] else amount
        description = " | ".join([raw["body"], *raw["lines"]])
        txn = Transaction(
            description_raw=description,
            amount=signed_amount,
            txn_date=parse_date(raw["date"]),
            direction="debit" if signed_amount < 0 else "credit",
            balance=float(raw["balance"].replace(",", "")),
        )

        upper = description.upper()
        if "SPANMRC" in upper or "MADA" in upper:
            txn.category = "pos_settlement" if signed_amount > 0 else "fee"
        elif "SFEEMRC" in upper or "FEE" in upper or "ضريبة" in description:
            txn.category = "fee"
        elif "TRANSFER" in upper or "FT" in upper:
            txn.category = "transfer_out" if signed_amount < 0 else "transfer_in"

        return txn
    except Exception:
        return None


def parse_alawwal_icorp_text(file_path: str):
    pages = extract_text_from_pdf(file_path)
    transactions = []
    current = None

    for page in pages:
        for raw_line in page["text"].splitlines():
            line = clean_line(raw_line)
            if not line:
                continue

            amount_match = AL_AWWAL_AMOUNT_RE.match(line)
            if amount_match:
                if current:
                    transactions.append(build_alawwal_transaction(current))
                current = {
                    "drcr": amount_match.group("drcr").upper(),
                    "amount": amount_match.group("amount"),
                    "headline": None,
                    "txn_date": None,
                    "lines": [],
                    "balance": None,
                }
                continue

            if not current:
                continue

            detail_match = AL_AWWAL_DETAIL_RE.match(line)
            if detail_match and current["headline"] is None:
                current["headline"] = detail_match.group("body")
                current["txn_date"] = detail_match.group("txn_date")
                continue

            balance_match = re.search(r"SAR\s+([\d,]+\.\d{2})", line, re.IGNORECASE)
            if balance_match and current["balance"] is None:
                current["balance"] = balance_match.group(1)
                continue

            if line.startswith(("صفحة", "Page ")):
                continue

            current["lines"].append(line)

    if current:
        transactions.append(build_alawwal_transaction(current))

    return [txn for txn in transactions if txn is not None]


def parse_alawwal_statement_text(file_path: str):
    pages = extract_text_from_pdf(file_path)
    transactions = []
    current = None

    for page in pages:
        for raw_line in page["text"].splitlines():
            line = clean_line(raw_line)
            if not line:
                continue

            match = AL_AWWAL_STATEMENT_RE.match(line)
            if match:
                if current:
                    transactions.append(build_alawwal_statement_transaction(current))
                current = {
                    "date": match.group("date"),
                    "body": match.group("body"),
                    "amount": match.group("amount"),
                    "balance": match.group("balance"),
                    "lines": [],
                }
                continue

            if current:
                upper = line.upper()
                if upper.startswith(("DATE TRANSACTION TYPE", "TRANSACTION DETAILS", "PAGE ")):
                    continue
                if "ACCOUNT STATEMENT" in upper or "REFERENCE NO." in upper:
                    continue
                current["lines"].append(line)

    if current:
        transactions.append(build_alawwal_statement_transaction(current))

    return [txn for txn in transactions if txn is not None]


def parse_bsf_transaction_history_text(file_path: str):
    pages = extract_text_from_pdf(file_path)
    lines = []

    for page in pages:
        for raw_line in page["text"].splitlines():
            line = clean_line(raw_line)
            if line:
                lines.append(line)

    opening_balance = extract_opening_balance(lines)
    rows = []
    pending_context = []
    current = None

    def is_next_context_start(value: str) -> bool:
        upper = value.upper()
        return any(term in upper for term in [
            "SADAD PAYMENT",
            "INCOMING TRANSFER",
            "OUTWARD TRANSFER",
            "ACCOUNT TO ACCOUNT TRANSFER",
            "CHEQUE DEPOSIT",
            "CHARGES/",
            "CHARGES ",
            "IPS INCOMING",
        ])

    def is_noise(value: str) -> bool:
        upper = value.upper()
        return (
            upper.startswith(("ACCOUNT DETAILS", "GENERAL DETAILS", "TRANSACTIONS LIST"))
            or "TRANSACTION VALUE DATE" in upper
            or "DATE AND TIME:" in upper
            or upper.startswith(("OPENING BALANCE", "DATE FROM"))
        )

    def finish_current():
        nonlocal current
        if current:
            rows.append(current)
            current = None

    for line in lines:
        match = BSF_TXN_RE.match(line)
        if not match:
            if is_noise(line):
                continue

            if current and is_next_context_start(line):
                finish_current()
                pending_context = [line]
                continue

            if current:
                current["tail"].append(line)
                continue

            pending_context.append(line)
            pending_context = pending_context[-8:]
            continue

        middle = match.group("middle")
        if "NMSC" not in middle.upper():
            if current:
                current["tail"].append(line)
            else:
                pending_context.append(line)
                pending_context = pending_context[-8:]
            continue

        finish_current()
        current = {
            "txn_date": match.group("txn_date"),
            "middle": middle,
            "amount": match.group("amount"),
            "balance": match.group("balance"),
            "description": match.group("description") or "",
            "context": pending_context,
            "tail": [],
        }
        pending_context = []

    finish_current()

    transactions = []
    previous_balance = opening_balance

    for row in rows:
        txn = build_bsf_transaction(row, previous_balance)
        if txn:
            transactions.append(txn)
            previous_balance = txn.balance

    return transactions


def build_bsf_transaction(row, previous_balance):
    try:
        amount = float(row["amount"].replace(",", ""))
        balance = float(row["balance"].replace(",", ""))
        description_parts = [
            *row.get("context", []),
            row["middle"],
            row["description"],
            *row.get("tail", []),
        ]
        description = " | ".join(part for part in description_parts if part)
        upper = description.upper()

        signed_amount = amount
        if previous_balance is not None:
            credit_delta = round(previous_balance + amount - balance, 2)
            debit_delta = round(previous_balance - amount - balance, 2)
            if abs(credit_delta) <= 0.05:
                signed_amount = amount
            elif abs(debit_delta) <= 0.05:
                signed_amount = -amount
            elif any(term in upper for term in ["BEN:", "DEBIT", "CHARGES", "SADAD", "BILLER"]):
                signed_amount = -amount
        elif any(term in upper for term in ["BEN:", "DEBIT", "CHARGES", "SADAD", "BILLER"]):
            signed_amount = -amount

        txn = Transaction(
            description_raw=description,
            amount=signed_amount,
            txn_date=parse_date(row["txn_date"]),
            direction="debit" if signed_amount < 0 else "credit",
            balance=balance,
        )

        if "CHARGES" in upper or "VAT" in upper:
            txn.category = "fee"
        elif "SADAD" in upper or "BILLER:" in upper:
            txn.category = "bill_payment"
        elif "DISCOUNTING PAYMENT" in upper:
            txn.category = "invoice_discounting"
        elif "PAYROLL" in upper or "SALARY" in upper:
            txn.category = "salary_payment" if signed_amount < 0 else "salary"
        elif "BEN:" in upper or "DEBIT" in upper:
            txn.category = "transfer_out"
        elif "REM:" in upper or "CREDIT" in upper:
            txn.category = "transfer_in"

        return txn
    except Exception:
        return None


def build_alawwal_statement_transaction(raw):
    try:
        amount = float(raw["amount"].replace(",", ""))
        balance = float(raw["balance"].replace(",", ""))
        description = " | ".join([raw["body"], *raw["lines"]])
        upper = description.upper()

        debit_terms = [
            "OUTGOING",
            "CHARGES",
            "FEE",
            "REPAY",
            "POS PURCHASE",
            "WITHDRAWAL",
        ]
        is_debit = any(term in upper for term in debit_terms)
        signed_amount = -amount if is_debit else amount

        txn = Transaction(
            description_raw=description,
            amount=signed_amount,
            txn_date=parse_date(raw["date"]),
            direction="debit" if signed_amount < 0 else "credit",
            balance=balance,
        )

        if "CHARGES" in upper or "FEE" in upper:
            txn.category = "fee"
        elif "OUTGOING" in upper:
            txn.category = "transfer_out"
        elif "TRANSFER" in upper:
            txn.category = "transfer_in" if signed_amount > 0 else "transfer_out"
        elif "REPAY" in upper:
            txn.category = "loan_repayment"

        return txn
    except Exception:
        return None


def build_alawwal_transaction(raw):
    try:
        amount = float(raw["amount"].replace(",", ""))
        signed_amount = -amount if raw["drcr"] == "DR" else amount
        description_parts = [raw["headline"] or "", *raw["lines"]]
        description = " | ".join(part for part in description_parts if part)
        balance = float(raw["balance"].replace(",", "")) if raw["balance"] else None

        txn = Transaction(
            description_raw=description,
            amount=signed_amount,
            txn_date=parse_date(raw["txn_date"]) if raw["txn_date"] else None,
            direction="debit" if signed_amount < 0 else "credit",
            balance=balance,
        )

        upper = description.upper()
        if "FEE" in upper or "CHARGES" in upper or "VAT" in upper or "رسوم" in description:
            txn.category = "fee"
        elif "SETL" in upper or "POS" in upper and signed_amount > 0:
            txn.category = "pos_settlement"
        elif "حوالة" in description or "TRANSFER" in upper:
            txn.category = "transfer_out" if signed_amount < 0 else "transfer_in"

        return txn
    except Exception:
        return None


def build_generic_transaction(match):
    try:
        amount = float(match.group("amount").replace(",", ""))
        drcr = (match.group("drcr") or "").upper()

        if drcr in {"DR", "DEBIT"}:
            signed_amount = -abs(amount)
            direction = "debit"
        elif drcr in {"CR", "CREDIT"}:
            signed_amount = abs(amount)
            direction = "credit"
        else:
            signed_amount = amount
            direction = "credit" if amount > 0 else "debit"

        balance = None
        if match.group("balance"):
            balance = float(match.group("balance").replace(",", ""))

        txn = Transaction(
            description_raw=match.group("body").strip(),
            amount=signed_amount,
            txn_date=parse_date(match.group("date")),
            direction=direction,
            balance=balance,
        )

        return txn
    except Exception:
        return None


def build_transaction(raw):
    try:
        headline = raw["headline"]
        drcr = raw["drcr"]
        amount = float(raw["amount"].replace(",", ""))

        if drcr.upper() == "DR":
            signed_amount = -amount
        else:
            signed_amount = amount

        extra_lines = raw["lines"]

        description_parts = [headline]
        for line in extra_lines:
            if line.startswith("Page No :-"):
                continue
            description_parts.append(line)

        description_raw = " | ".join(description_parts)
        balance = extract_balance(extra_lines)

        txn = Transaction(
            description_raw=description_raw,
            amount=signed_amount,
            txn_date=parse_date(raw["txn_date"]),
        )

        # optional dynamic field
        txn.balance = balance

        # useful starter rule-based hints
        headline_upper = headline.upper()

        if "CHARGES AND FEES" in headline_upper:
            txn.category = "fee"
            txn.direction = "debit"
        elif "OUTGOING TRANSFER" in headline_upper:
            txn.category = "transfer_out"
            txn.direction = "debit"
        elif "AC TO AC TRANSFER" in headline_upper and signed_amount < 0:
            txn.category = "transfer_out"
            txn.direction = "debit"
        elif "TRANSFER" in headline_upper and signed_amount > 0:
            txn.category = "transfer_in"
            txn.direction = "credit"

        return txn

    except Exception:
        return None


def _apply_parser_metadata(transactions, detection):
    parser_name = getattr(detection, "parser_name", None)
    source_bank = getattr(detection, "bank_name", None)
    confidence = getattr(detection, "confidence", None)
    warnings = list(getattr(detection, "warnings", []) or [])

    for txn in transactions:
        txn.parser_name = parser_name
        txn.source_bank = source_bank
        txn.parse_confidence = confidence
        txn.warnings.extend(warnings)

    return transactions


def parse_pdf(file_path: str, detection=None):
    parser_name = getattr(detection, "parser_name", "sabb_v1")

    if parser_name == "sabb_v1":
        transactions = parse_sabb_text(file_path)
    elif parser_name == "snb_business_v1":
        transactions = parse_snb_business_text(file_path)
    elif parser_name == "alawwal_icorp_v1":
        transactions = parse_alawwal_icorp_text(file_path)
    elif parser_name == "alawwal_statement_v1":
        transactions = parse_alawwal_statement_text(file_path)
    elif parser_name == "bsf_transaction_history_v1":
        transactions = parse_bsf_transaction_history_text(file_path)
    else:
        transactions = parse_generic_text(file_path)

    if detection:
        return _apply_parser_metadata(transactions, detection)

    return transactions
